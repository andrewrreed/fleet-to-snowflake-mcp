-- 01_setup.sql: warehouse, database, demo data, and the read-only runtime role.
-- Run as ACCOUNTADMIN. Idempotent. Only creates FLEET_MCP* objects.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS FLEET_MCP_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Fleet -> Snowflake MCP demo';

CREATE DATABASE IF NOT EXISTS FLEET_MCP COMMENT = 'Fleet -> Snowflake MCP demo';
CREATE SCHEMA IF NOT EXISTS FLEET_MCP.DATA;      -- copied TPCH tables
CREATE SCHEMA IF NOT EXISTS FLEET_MCP.SEMANTIC;  -- semantic views
CREATE SCHEMA IF NOT EXISTS FLEET_MCP.AGENTS;    -- Cortex Agent + MCP server

-- Copy the sample data so the demo owns its tables (no grants on the shared sample DB needed).
USE WAREHOUSE FLEET_MCP_WH;
CREATE TABLE IF NOT EXISTS FLEET_MCP.DATA.REGION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;
CREATE TABLE IF NOT EXISTS FLEET_MCP.DATA.NATION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;
CREATE TABLE IF NOT EXISTS FLEET_MCP.DATA.CUSTOMER AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;
CREATE TABLE IF NOT EXISTS FLEET_MCP.DATA.ORDERS   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
CREATE TABLE IF NOT EXISTS FLEET_MCP.DATA.LINEITEM AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;

-- Runtime role used by every MCP session (Fleet via OAuth, smoke test via key pair). Read-only.
CREATE ROLE IF NOT EXISTS FLEET_MCP_ROLE COMMENT = 'Read-only runtime role for Fleet MCP sessions';
GRANT USAGE ON WAREHOUSE FLEET_MCP_WH TO ROLE FLEET_MCP_ROLE;
GRANT USAGE ON DATABASE FLEET_MCP TO ROLE FLEET_MCP_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE FLEET_MCP TO ROLE FLEET_MCP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA FLEET_MCP.DATA TO ROLE FLEET_MCP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE FLEET_MCP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE FLEET_MCP_ROLE;

-- The demo user. MCP sessions run as the user's DEFAULT_ROLE and need a DEFAULT_WAREHOUSE.
GRANT ROLE FLEET_MCP_ROLE TO USER {{SNOWFLAKE_USER}};
ALTER USER {{SNOWFLAKE_USER}} SET DEFAULT_ROLE = FLEET_MCP_ROLE DEFAULT_WAREHOUSE = FLEET_MCP_WH;
